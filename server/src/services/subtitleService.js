import fs from 'fs';
import path from 'path';
import Groq from 'groq-sdk';
import ffmpeg from 'fluent-ffmpeg';
import ffmpegInstaller from '@ffmpeg-installer/ffmpeg';
import { logger } from '../utils/logger.js';

ffmpeg.setFfmpegPath(ffmpegInstaller.path);

const CACHE_DIR = path.join(process.cwd(), 'media_cache');
if (!fs.existsSync(CACHE_DIR)) {
  fs.mkdirSync(CACHE_DIR, { recursive: true });
}

function formatVttTime(seconds) {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(ms).padStart(3, '0')}`;
}

function extractAudio(videoPath, audioPath) {
  return new Promise((resolve, reject) => {
    logger.info(`Extracting lightweight audio from ${videoPath} to ${audioPath}...`);
    ffmpeg(videoPath)
      .noVideo()
      .audioCodec('libmp3lame')
      .audioBitrate(32)
      .audioChannels(1)
      .save(audioPath)
      .on('end', () => {
        logger.info('✓ Audio extraction completed.');
        resolve();
      })
      .on('error', (err) => {
        logger.error({ err }, 'Error during audio extraction');
        reject(err);
      });
  });
}

export async function generateSubtitlesWithGroq(videoFilePath) {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) {
    throw new Error('GROQ_API_KEY is not configured in environment variables.');
  }

  const groq = new Groq({ apiKey });
  const audioPath = `${videoFilePath}.mp3`;

  try {
    await extractAudio(videoFilePath, audioPath);

    logger.info('Sending audio to Groq Whisper Large V3...');
    const transcription = await groq.audio.transcriptions.create({
      file: fs.createReadStream(audioPath),
      model: 'whisper-large-v3',
      response_format: 'verbose_json',
      temperature: 0.0,
      language: 'en'
    });

    let vtt = 'WEBVTT - Auto-Generated by Groq Whisper AI\n\n';

    if (transcription.segments && transcription.segments.length > 0) {
      for (const seg of transcription.segments) {
        const start = formatVttTime(seg.start);
        const end = formatVttTime(seg.end);
        vtt += `${start} --> ${end}\n${seg.text.trim()}\n\n`;
      }
    } else if (transcription.text) {
      vtt += `00:00:00.000 --> 00:01:00.000\n${transcription.text.trim()}\n\n`;
    }

    return vtt;
  } finally {
    if (fs.existsSync(audioPath)) {
      try {
        fs.unlinkSync(audioPath);
      } catch {}
    }
  }
}